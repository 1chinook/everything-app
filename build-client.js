'use strict';

const fs = require('node:fs');
const path = require('node:path');

const scripts = ['scenarios.js', 'daily.js', 'backups.js', 'materials.js', 'curiosity.js', 'books.js', 'app-core.js'];
const output = scripts.map(file => '// Source: ' + file + '\n' +
  fs.readFileSync(path.join(__dirname, file), 'utf8')).join('\n\n');
fs.writeFileSync(path.join(__dirname, 'app.js'), '// Generated by node build-client.js\n' + output);
console.log('Everything App browser bundle updated.');
